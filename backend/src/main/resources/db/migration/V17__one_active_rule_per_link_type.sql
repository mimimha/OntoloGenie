-- V17: 관계 유형마다 반영 중인(ACTIVE) 연결 규칙은 하나다 (S15P31C106-367)
--   같은 관계 유형에 다른 코드의 규칙이 둘 이상 반영 중이면, 한 출발을 서로 다른 도착으로 이으려 할 때 관계 수 제약 때문에
--   연결 재계산이 둘 다 빼고(규칙 충돌), 검사는 규칙마다 따로 봐서 이를 드러내지 못한다.
--   승인 반영(LinkRuleApplier)이 먼저 막고, 승인 반영을 거치지 않는 저장(직접 SQL 등)도 DB가 막는다.
--   규칙을 바꾸는 길은 같은 코드의 개정본이다. 개정은 이전 개정본을 RETIRED로 바꾼 뒤 새 개정본을 넣으므로 이 인덱스와 부딪치지 않는다.
--   기존 행은 바꾸지 않는다. 이미 중복이 있으면 이 마이그레이션이 실패하므로, 어느 규칙을 남길지 정해 정리한 뒤 적용한다.
-- =====================================================================

CREATE UNIQUE INDEX uq_link_mapping_active_link_type ON link_mapping (link_type_id) WHERE status = 'ACTIVE';

COMMENT ON INDEX uq_link_mapping_active_link_type IS '관계 유형마다 반영 중인 규칙은 하나(367). 규칙 충돌 예방. 규칙 코드마다 반영 중 개정본 하나(uq_link_mapping_active)와 함께 관계 유형·규칙 코드가 1:1이 된다';
