ALTER TABLE cdc_offset
    ADD COLUMN last_txid         xid8,
    ADD COLUMN last_commit_at    timestamptz,
    ADD COLUMN last_message_at   timestamptz,
    ADD COLUMN processing_lag_ms integer,
    ADD COLUMN healthy_since     timestamptz,
    ADD COLUMN recovery_reason   varchar(40),
    ADD COLUMN recovery_at       timestamptz,
    ADD CONSTRAINT ck_cdc_offset_lag      CHECK (processing_lag_ms IS NULL OR processing_lag_ms >= 0),
    ADD CONSTRAINT ck_cdc_offset_recovery CHECK ((recovery_reason IS NULL) = (recovery_at IS NULL)),
    ADD CONSTRAINT ck_cdc_offset_recovery_reason
