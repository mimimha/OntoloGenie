COMMENT ON COLUMN cdc_offset.last_message_at IS '변경·트랜잭션 경계·heartbeat 중 마지막으로 받은 메시지 시각(플랫폼 시계). 변경이 없는 원천도 커넥터가 살아 있음을 안다';
