-- 2. 수집 실패 기록
CREATE TABLE source_load_failure (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_resource_id       bigint       NOT NULL REFERENCES source_resource (id) ON DELETE CASCADE,
    object_source_mapping_id bigint       NOT NULL REFERENCES object_source_mapping (id) ON DELETE CASCADE,
    source_key               jsonb,
    column_name              varchar(200) NOT NULL,
    property_definition_id   bigint       REFERENCES property_definition (id) ON DELETE CASCADE,
    reason                   varchar(30)  NOT NULL,
    status                   varchar(10)  NOT NULL DEFAULT 'OPEN',
    occurrences              integer      NOT NULL DEFAULT 1,
    first_seen_at            timestamptz  NOT NULL DEFAULT now(),
    last_seen_at             timestamptz  NOT NULL DEFAULT now(),
    last_sync_run_id         bigint       NOT NULL REFERENCES sync_run (id) ON DELETE RESTRICT,
    closed_at                timestamptz,
    CONSTRAINT ck_source_load_failure_reason
        CHECK (reason IN ('KEY_MISSING', 'KEY_UNSUPPORTED', 'VALUE_CONVERSION', 'UNSUPPORTED_TYPE')),
    CONSTRAINT ck_source_load_failure_status CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT ck_source_load_failure_closed CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL)),
    CONSTRAINT ck_source_load_failure_key    CHECK (source_key IS NULL OR jsonb_typeof(source_key) = 'object'),
    CONSTRAINT ck_source_load_failure_count  CHECK (occurrences > 0),
    CONSTRAINT ck_source_load_failure_seen   CHECK (last_seen_at >= first_seen_at)
);
-- 같은 실패는 열린 기록 하나에 횟수만 올린다. 키가 없는 실패는 매핑·컬럼·사유가 같으면 하나로 모은다
CREATE UNIQUE INDEX uq_source_load_failure_open ON source_load_failure
    (object_source_mapping_id, source_key, column_name, reason) NULLS NOT DISTINCT WHERE status = 'OPEN';
CREATE INDEX ix_source_load_failure_resource ON source_load_failure (source_resource_id) WHERE status = 'OPEN';
CREATE INDEX ix_source_load_failure_run ON source_load_failure (last_sync_run_id);

COMMENT ON TABLE source_load_failure IS '수집 실패 기록(결정 9.2). 전체 읽기(197)·CDC(198)가 객체로 만들지 못한 원천 행(키 없음·키 형식 미지원)과 속성 값 변환 실패. 원천 행 값은 복사하지 않고 키와 실패 컬럼만 남긴다. issue로 올리지 않는다(issue는 연결 규칙·후보에서 나온 정합성 문제). 도착 표의 연결 기준 컬럼에 열린 기록이 있으면 그 규칙의 미연결 판정을 보류한다(설계 검토 R5). 074 수집 이력에서 보여 준다';
COMMENT ON COLUMN source_load_failure.source_key IS '원천 키(컬럼 → 키 문자열). 키를 만들지 못한 행이면 NULL';
COMMENT ON COLUMN source_load_failure.column_name IS '실패한 원천 컬럼. 키 실패면 그 키 컬럼';
COMMENT ON COLUMN source_load_failure.property_definition_id IS '속성 값 변환 실패면 그 속성. 키 실패면 NULL';
COMMENT ON COLUMN source_load_failure.reason IS 'KEY_MISSING 키 값 없음, KEY_UNSUPPORTED 키로 쓸 수 없는 형식, VALUE_CONVERSION 속성 자료형으로 바꾸지 못함, UNSUPPORTED_TYPE 지원하지 않는 원천 형식(bytea·배열 등)';
COMMENT ON COLUMN source_load_failure.status IS 'OPEN 실패 중, CLOSED 같은 키·속성이 다시 성공적으로 쓰였거나 다음 전체 읽기에서 다시 나오지 않음';
COMMENT ON COLUMN source_load_failure.occurrences IS '열린 동안 같은 실패를 본 횟수. 실행마다 행을 새로 만들지 않는다';
COMMENT ON COLUMN source_load_failure.last_sync_run_id IS '마지막으로 이 실패를 본 수집 실행';

-- 3. 확인 대기
CREATE TABLE link_check_pending (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_mapping_id   bigint      NOT NULL REFERENCES link_mapping (id) ON DELETE RESTRICT,
    source_object_id  bigint      NOT NULL REFERENCES object_instance (id) ON DELETE RESTRICT,
    status            varchar(20) NOT NULL DEFAULT 'WAITING',
    first_seen_at     timestamptz NOT NULL DEFAULT now(),
    last_check_run_id bigint      NOT NULL REFERENCES check_run (id) ON DELETE RESTRICT,
    closed_at         timestamptz,
    close_reason      varchar(20),
    issue_id          bigint      REFERENCES issue (id) ON DELETE RESTRICT,
    CONSTRAINT ck_link_check_pending_status CHECK (status IN ('WAITING', 'TRANSIENT', 'PROMOTED')),
    CONSTRAINT ck_link_check_pending_closed CHECK ((status = 'WAITING') = (closed_at IS NULL)),
    CONSTRAINT ck_link_check_pending_time   CHECK (closed_at IS NULL OR closed_at >= first_seen_at),
    CONSTRAINT ck_link_check_pending_reason CHECK (
        (status = 'WAITING' AND close_reason IS NULL)
        OR (status = 'TRANSIENT' AND close_reason IN ('LINKED', 'SOURCE_DELETED', 'RULE_RETIRED'))
        OR (status = 'PROMOTED' AND close_reason = 'PROMOTED')),
    CONSTRAINT ck_link_check_pending_issue  CHECK ((status = 'PROMOTED') = (issue_id IS NOT NULL))
);
-- 같은 규칙·출발 객체는 대기 중인 것 하나
CREATE UNIQUE INDEX uq_link_check_pending_waiting ON link_check_pending (link_mapping_id, source_object_id) WHERE status = 'WAITING';
CREATE INDEX ix_link_check_pending_first_seen ON link_check_pending (first_seen_at) WHERE status = 'WAITING';
CREATE INDEX ix_link_check_pending_issue ON link_check_pending (issue_id) WHERE issue_id IS NOT NULL;

COMMENT ON TABLE link_check_pending IS '확인 대기(결정 8장 ②). 원천 사이 규칙(ERP ↔ MES)과 FULL_COMPARE 표가 걸린 규칙에서 SYNC가 찾은 미연결을 바로 issue로 만들지 않고 둔다. 그 사이 연결되거나 출발 객체가 지워지면 일시 불일치(TRANSIENT)로 닫고, 출발·도착 원천이 정상인 채로 대기 시간이 지나도 안 맞으면 issue(UNMATCHED)로 올린다(PROMOTED). 실질 대기 시작은 max(first_seen_at, 양쪽 원천의 cdc_offset.healthy_since). 승격과 issue 등록은 한 트랜잭션이다. 원천 사이 issue의 의미는 "수집이 정상인 상태에서 지속된 불일치 관찰"이다. 같은 원천 규칙은 대기 없이 바로 판정한다';
COMMENT ON COLUMN link_check_pending.link_mapping_id IS '미연결을 찾은 규칙 개정본. 개정본이 RETIRED가 되면 TRANSIENT·RULE_RETIRED로 닫는다';
COMMENT ON COLUMN link_check_pending.first_seen_at IS '처음 미연결로 본 시각';
COMMENT ON COLUMN link_check_pending.last_check_run_id IS '마지막으로 이 대기를 확인한 SYNC 검사';
COMMENT ON COLUMN link_check_pending.status IS 'WAITING 대기, TRANSIENT 일시 불일치로 자동 종료, PROMOTED issue로 승격';
COMMENT ON COLUMN link_check_pending.close_reason IS 'LINKED 연결됨, SOURCE_DELETED 출발 객체가 원천에서 지워짐, RULE_RETIRED 규칙 개정본이 바뀜, PROMOTED 승격';
COMMENT ON COLUMN link_check_pending.issue_id IS '승격해 만든 issue';

-- 4. SYNC 검사는 배치가 모아서 돌린다. 한 실행이 여러 수집 묶음에 걸치므로 sync_run_id는 선택이다(어느 시점 데이터인지는 data_basis)
ALTER TABLE check_run DROP CONSTRAINT ck_check_run_sync;
ALTER TABLE check_run ADD CONSTRAINT ck_check_run_sync CHECK (trigger_kind = 'SYNC' OR sync_run_id IS NULL);

