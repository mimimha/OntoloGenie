-- ---------------------------------------------------------------------
-- 4. 정합성 검사·문제 (FN-CHK-01~06, FN-ISS-01~04, 결정 8·10)
-- ---------------------------------------------------------------------

-- [2026-10-27] 정기 자동 검사는 두지 않는다. 수집이 승인된 규칙으로 연결을 계산하면서 행마다 정상·미연결·중복·조건 위반으로
--   나누고 문제를 등록한다. 그 결과를 trigger_kind=SYNC 검사 실행으로 남긴다. 수동 검사·재검증·후보 시험은 유지.
--   원천을 읽어야 하는 검사(새 유형 후보 시험)는 백엔드가 QUEUED로 넣고 배치가 실행한다(백엔드는 원천에 붙지 않음).

CREATE TABLE check_run (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_kind       varchar(20) NOT NULL,
    status             varchar(20) NOT NULL DEFAULT 'QUEUED',
    scope              jsonb       NOT NULL DEFAULT '{}'::jsonb,   -- 대상 규칙·후보·문제 목록
    work_key           varchar(300) NOT NULL,                     -- [A4] 대상(규칙 개정본·후보 revision 목록) + data_basis를 정규화한 키
    data_basis         jsonb       NOT NULL DEFAULT '{}'::jsonb,  -- [A4] 시작 시점의 기준: 관계된 원천 테이블별 체크포인트. 스냅샷으로 읽은 데이터가 어느 시점인지
    sync_run_id        bigint      REFERENCES sync_run (id) ON DELETE RESTRICT,   -- SYNC면 그 분류를 만든 수집
    compared_to_run_id bigint      REFERENCES check_run (id) ON DELETE RESTRICT,  -- 재검증 비교 대상(FN-CHK-06)
    requested_by       bigint      REFERENCES account (id) ON DELETE RESTRICT,
    requested_at       timestamptz NOT NULL DEFAULT now(),
    started_at         timestamptz,
    finished_at        timestamptz,
    error_message      text,
    CONSTRAINT ck_check_run_trigger  CHECK (trigger_kind IN ('MANUAL', 'SYNC', 'REVERIFY', 'CANDIDATE')),  -- CANDIDATE: 후보 생성·수정 시 자동 시험(2026-10-23)
    CONSTRAINT ck_check_run_status   CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_check_run_started  CHECK ((status = 'QUEUED') = (started_at IS NULL)),
    CONSTRAINT ck_check_run_finished CHECK ((status IN ('SUCCEEDED', 'FAILED')) = (finished_at IS NOT NULL)),
    CONSTRAINT ck_check_run_manual   CHECK (trigger_kind IN ('SYNC', 'CANDIDATE') OR requested_by IS NOT NULL),  -- 수집 중 분류·AI 후보 시험은 요청자가 없을 수 있다
    CONSTRAINT ck_check_run_sync     CHECK ((trigger_kind = 'SYNC') = (sync_run_id IS NOT NULL)),
    CONSTRAINT ck_check_run_reverify CHECK (trigger_kind <> 'REVERIFY' OR compared_to_run_id IS NOT NULL),
