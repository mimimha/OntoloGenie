CREATE TABLE proposal_item (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_run_id bigint       REFERENCES analysis_run (id) ON DELETE RESTRICT,
    origin          varchar(20)  NOT NULL,
    item_kind       varchar(30)  NOT NULL,
    revision        integer      NOT NULL DEFAULT 1,         -- 후보를 고칠 때마다 1 증가(FN-REV-03)
    payload         jsonb        NOT NULL,
    evidence        jsonb        NOT NULL DEFAULT '{}'::jsonb,  -- 원천 표·컬럼·값, 문서 원문, 제안 이유
    ai_confidence   numeric(5,4),                              -- AI 추정치. 검토 화면 "AI 신뢰도" 별도 칸. 시험 매칭률과 섞지 않음 [O1]
    review_status   varchar(20)  NOT NULL DEFAULT 'PENDING',
    apply_status    varchar(20)  NOT NULL DEFAULT 'NOT_APPLIED',
    apply_error     text,
    applied_at      timestamptz,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    created_by      bigint       REFERENCES account (id) ON DELETE RESTRICT,
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    updated_by      bigint       REFERENCES account (id) ON DELETE RESTRICT,
    row_version     integer      NOT NULL DEFAULT 0,
    CONSTRAINT ck_proposal_item_origin CHECK (origin IN ('AI', 'MANUAL')),
    CONSTRAINT ck_proposal_item_kind CHECK (item_kind IN (
        'OBJECT_TYPE', 'PROPERTY', 'LINK_TYPE', 'OBJECT_MAPPING', 'PROPERTY_MAPPING', 'LINK_RULE', 'DOCUMENT_LINK')),
    CONSTRAINT ck_proposal_item_ai     CHECK (origin <> 'AI' OR analysis_run_id IS NOT NULL),
    CONSTRAINT ck_proposal_item_manual CHECK (origin <> 'MANUAL' OR created_by IS NOT NULL),
    CONSTRAINT ck_proposal_item_conf   CHECK (ai_confidence IS NULL OR ai_confidence BETWEEN 0 AND 1),
    CONSTRAINT ck_proposal_item_revision CHECK (revision > 0),
    CONSTRAINT ck_proposal_item_review CHECK (review_status IN ('PENDING', 'APPROVED', 'REJECTED', 'HELD')),
    CONSTRAINT ck_proposal_item_apply  CHECK (apply_status IN ('NOT_APPLIED', 'APPLIED', 'FAILED')),
    CONSTRAINT ck_proposal_item_applied CHECK (apply_status <> 'APPLIED' OR (review_status = 'APPROVED' AND applied_at IS NOT NULL)),
    CONSTRAINT ck_proposal_item_failed CHECK (apply_status <> 'FAILED' OR apply_error IS NOT NULL),
    CONSTRAINT ck_proposal_item_payload CHECK (jsonb_typeof(payload) = 'object')
);
COMMENT ON TABLE  proposal_item IS 'AI 제안 또는 관리자가 직접 추가한 연결 규칙(FN-REV-02). 검토 상태와 반영 상태를 따로 관리(FN-REV-04). 승인하면 즉시 반영(FN-REV-06)';
COMMENT ON COLUMN proposal_item.payload IS '현재 revision의 내용(조회용 사본). 아직 없는 정의는 code로 참조한다. 검사·결정의 기준은 proposal_revision';

-- 후보 개정본: revision마다 한 행, 생성 후 수정·삭제 불가. 검사와 결정은 이 행을 가리킨다
CREATE TABLE proposal_revision (
    proposal_item_id bigint      NOT NULL REFERENCES proposal_item (id) ON DELETE RESTRICT,
    revision         integer     NOT NULL,
    payload          jsonb       NOT NULL,
    evidence         jsonb       NOT NULL DEFAULT '{}'::jsonb,
    ai_confidence    numeric(5,4),
    created_at       timestamptz NOT NULL DEFAULT now(),
    created_by       bigint      REFERENCES account (id) ON DELETE RESTRICT,   -- AI가 만들면 NULL
    PRIMARY KEY (proposal_item_id, revision),
    CONSTRAINT ck_proposal_revision_no      CHECK (revision > 0),
    CONSTRAINT ck_proposal_revision_payload CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT ck_proposal_revision_conf    CHECK (ai_confidence IS NULL OR ai_confidence BETWEEN 0 AND 1)
);
COMMENT ON TABLE proposal_revision IS '후보의 revision별 불변 내용. 후보를 고치면 새 revision 행을 추가하고 proposal_item.revision·payload를 그 값으로 바꾼다';

-- 제안 항목의 현재 revision은 반드시 개정본으로 존재해야 한다(같은 트랜잭션에서 넣도록 지연 검사)
ALTER TABLE proposal_item
    ADD CONSTRAINT fk_proposal_item_current_revision
    FOREIGN KEY (id, revision) REFERENCES proposal_revision (proposal_item_id, revision)
    DEFERRABLE INITIALLY DEFERRED;

