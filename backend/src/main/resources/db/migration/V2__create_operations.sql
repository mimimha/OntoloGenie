CREATE TABLE analysis_run (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_kind             varchar(20) NOT NULL,
    analysis_range       jsonb       NOT NULL DEFAULT '{}'::jsonb,   -- 분석 범위(기간 등). 테이블별로 고른 컬럼은 {"columns": {"<resource_id>": ["col", ...]}}, 없으면 전체(FN-SRC-03)
    work_key             varchar(300) NOT NULL,                    -- [A4] 원천 + 대상 테이블·문서 + 고른 컬럼(없으면 전체) + 변경 구간을 정규화한 키. 같은 키가 대기·실행 중이면 합류
    status               varchar(20) NOT NULL DEFAULT 'QUEUED',
    requested_by         bigint      NOT NULL REFERENCES account (id) ON DELETE RESTRICT,
    based_on_sync_run_id bigint      REFERENCES sync_run (id) ON DELETE RESTRICT,  -- 참고: 재분석을 촉발한 수집. 대상 구간은 analysis_run_target
    requested_at         timestamptz NOT NULL DEFAULT now(),
    started_at           timestamptz,
    finished_at          timestamptz,
    result_summary       jsonb       NOT NULL DEFAULT '{}'::jsonb,
    error_message        text,
    CONSTRAINT ck_analysis_run_kind     CHECK (run_kind IN ('INITIAL', 'REANALYSIS')),
    CONSTRAINT ck_analysis_run_status   CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_analysis_run_finished CHECK ((status IN ('SUCCEEDED', 'FAILED')) = (finished_at IS NOT NULL)),
    CONSTRAINT ck_analysis_run_error    CHECK (status <> 'FAILED' OR error_message IS NOT NULL)
);
COMMENT ON TABLE analysis_run IS 'AI 분석·추출·후보 생성 실행. 재분석(S5-4)은 변경된 데이터만 대상으로 한다. REANALYSIS의 대상 구간은 analysis_run_target에 고정한다(Handler 검사). 같은 work_key가 대기·실행 중이면 새로 만들지 않고 합류한다(A4)';
CREATE UNIQUE INDEX uq_analysis_run_active ON analysis_run (work_key) WHERE status IN ('QUEUED', 'RUNNING');

CREATE TABLE analysis_run_target (
    analysis_run_id    bigint NOT NULL REFERENCES analysis_run (id) ON DELETE CASCADE,
    source_resource_id bigint NOT NULL REFERENCES source_resource (id) ON DELETE RESTRICT,
    change_seq_from    bigint,      -- 재분석 대상 원천 변경 이력 구간(포함). 이 테이블의 변경 번호(2026-10-26 테이블 단위 체크포인트)
    change_seq_to      bigint,
    PRIMARY KEY (analysis_run_id, source_resource_id),
    CONSTRAINT ck_analysis_run_target_range CHECK (
        (change_seq_from IS NULL) = (change_seq_to IS NULL)
        AND (change_seq_from IS NULL OR change_seq_to >= change_seq_from))
);
COMMENT ON TABLE analysis_run_target IS '관리자가 고른 분석 대상 표·문서·메모(FN-SRC-03). 재분석이면 변경 구간을 고정해 두고, 대상 행은 원천 변경 이력에서 다시 찾는다(원천은 변경 이력을 보존해야 함)';

