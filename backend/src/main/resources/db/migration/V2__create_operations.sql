COMMENT ON TABLE proposal_option IS '같은 대상에 후보가 여럿일 때의 선택지(FN-REV-03). revision별로 고정되며 수정·삭제 불가';

-- 개정본·선택지 불변
CREATE FUNCTION guard_immutable_row() RETURNS trigger LANGUAGE plpgsql
    SET search_path = platform, pg_temp
AS $$
BEGIN
    RAISE EXCEPTION '% 행은 만든 뒤 수정·삭제할 수 없습니다. 새 revision을 만드세요', TG_TABLE_NAME;
END $$;
CREATE TRIGGER trg_proposal_revision_immutable BEFORE UPDATE OR DELETE ON proposal_revision
    FOR EACH ROW EXECUTE FUNCTION guard_immutable_row();
CREATE TRIGGER trg_proposal_option_immutable BEFORE UPDATE OR DELETE ON proposal_option
    FOR EACH ROW EXECUTE FUNCTION guard_immutable_row();

CREATE TABLE review_decision (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_item_id   bigint      NOT NULL,
    item_revision      integer     NOT NULL,
    decision           varchar(20) NOT NULL,
    selected_option_id bigint,
    reason             text        NOT NULL,                 -- 판단 사유 필수(S2-4)
    decided_by         bigint      NOT NULL REFERENCES account (id) ON DELETE RESTRICT,
    decided_at         timestamptz NOT NULL DEFAULT now(),
    -- 결정 대상 revision은 실제 개정본이어야 한다
    CONSTRAINT fk_review_decision_revision
        FOREIGN KEY (proposal_item_id, item_revision)
        REFERENCES proposal_revision (proposal_item_id, revision) ON DELETE RESTRICT,
    -- 고른 선택지는 같은 제안 항목, 같은 revision의 선택지여야 한다
    CONSTRAINT fk_review_decision_option
        FOREIGN KEY (selected_option_id, proposal_item_id, item_revision)
        REFERENCES proposal_option (id, proposal_item_id, revision) ON DELETE RESTRICT,
    CONSTRAINT ck_review_decision CHECK (decision IN ('APPROVE', 'REJECT', 'HOLD')),
    CONSTRAINT ck_review_decision_reason CHECK (length(btrim(reason)) > 0)
);
COMMENT ON TABLE review_decision IS '승인·거절·보류 결정과 사유. 결정할 때마다 한 행(이력). Admin만 결정, 승인은 같은 revision의 성공한 검사 결과가 있고 그 revision이 현재 revision일 때만(Handler)';

