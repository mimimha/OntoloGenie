CREATE TABLE role (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(30)  NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    CONSTRAINT ck_role_code CHECK (code IN ('ADMIN', 'PLANNER', 'MAINTENANCE', 'VIEWER'))
);
COMMENT ON TABLE role IS '역할 4개 고정(최종 시나리오 S7). 역할 추가·편집 화면은 두지 않는다';

CREATE TABLE permission (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        varchar(100) NOT NULL UNIQUE,
    name        varchar(200) NOT NULL,
    description text
);
COMMENT ON TABLE permission IS '서버가 검사하는 권한 코드. action_definition.required_permission이 참조. [미정 U5] 코드 목록은 FN-ADM-04에서 구체화';

CREATE TABLE role_permission (
    role_id       bigint NOT NULL REFERENCES role (id) ON DELETE CASCADE,
    permission_id bigint NOT NULL REFERENCES permission (id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE role_data_scope (
    role_id             bigint       NOT NULL REFERENCES role (id) ON DELETE CASCADE,
    access_group        varchar(100) NOT NULL,      -- object_type.access_group 값
    can_view_restricted boolean      NOT NULL DEFAULT false,  -- sensitivity=RESTRICTED 속성 열람
    PRIMARY KEY (role_id, access_group)
);
COMMENT ON TABLE role_data_scope IS '역할별 조회 범위. [미정 U5 — 방향 합의] ADMIN은 전체 조회·승인·반영, 나머지는 조회만. 제한은 유형 단위(access_group)와 속성 단위(민감 열람) 두 축이고 행 단위 제한은 MVP 밖. 값은 팀 협의. 결정 11: MVP에서 MAINTENANCE는 VIEWER와 같게 둔다';

CREATE TABLE account (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id             varchar(100) NOT NULL UNIQUE,
    display_name         varchar(100) NOT NULL,
    password_hash        varchar(255) NOT NULL,     -- 해시만 저장(D04)
    role_id              bigint       NOT NULL REFERENCES role (id) ON DELETE RESTRICT,
    status               varchar(20)  NOT NULL DEFAULT 'ACTIVE',
    must_change_password boolean      NOT NULL DEFAULT true,   -- 임시 비밀번호(D03)
    password_changed_at  timestamptz,
    failed_login_count   integer      NOT NULL DEFAULT 0,
    last_login_at        timestamptz,
    created_at           timestamptz  NOT NULL DEFAULT now(),
    created_by           bigint       REFERENCES account (id) ON DELETE RESTRICT,  -- 최초 관리자는 NULL(D02)
    updated_at           timestamptz  NOT NULL DEFAULT now(),
    updated_by           bigint       REFERENCES account (id) ON DELETE RESTRICT,
    row_version          integer      NOT NULL DEFAULT 0,
    CONSTRAINT ck_account_status   CHECK (status IN ('ACTIVE', 'LOCKED', 'DISABLED')),
    CONSTRAINT ck_account_failures CHECK (failed_login_count >= 0)
);
COMMENT ON TABLE account IS '공개 가입 없음(D01). 계정은 지우지 않고 DISABLED로 둔다(D06). 사용자당 역할 하나';

